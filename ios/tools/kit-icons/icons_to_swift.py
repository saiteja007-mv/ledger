#!/usr/bin/env python3
"""Turns icons.json (the Finance Mobile App UI Kit's 24 px icons: name -> SVG path data) into
Sources/Ledger/Kit/KitIcons.swift.

Run from Ledger/:  python3 tools/kit-icons/icons_to_swift.py
Every icon is a 24 x 24 outline filled with the kit's ink and drawn even-odd, so a path is all it holds.
The JSON came from the kit's Icons frame (Figma file UgKR3F5A0WAXKsLaB46Hjb, page Components)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "Sources", "Ledger", "Kit", "KitIcons.swift")


def main():
    with open(os.path.join(HERE, "icons.json"), encoding="utf-8") as fh:
        icons = json.load(fh)
    lines = ["// Generated by tools/kit-icons/icons_to_swift.py from the Finance Mobile App UI Kit's icons. Do not edit by hand.", "",
             "extension KitIcon {"]
    for name in sorted(icons):
        lines.append(f"    static let {name} = KitIcon(width: 24, height: 24, elements: [")
        for d in icons[name]:
            lines.append(f'        .init(d: "{d}", fill: .ink, evenOdd: true),')
        lines.append("    ])")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(OUT), len(icons), "icons")


main()
