/// The kit's gold coin (the 24 and 44 px Coin icons are a ring with a dollar sign): a yellow disc with a
/// black rim and an inner ring, drawn natively so it sits on the blue banner and the account cards.
struct KitCoin: View {
    var size: CGFloat = 44

    var body: some View {
        ZStack {
            Circle().fill(KitColor.yellow)
            Circle().stroke(KitColor.black, lineWidth: max(1.2, size / 22))
            Circle()
                .stroke(KitColor.black, lineWidth: max(1, size / 30))
                .padding(size * 0.2)
            Text("$")
                .font(.kit(.medium, size * 0.34))
                .foregroundStyle(KitColor.black)
        }
        .frame(width: size, height: size)
        .accessibilityHidden(true)
    }
}
